-- Assinatura: só o que muda a MC (valores e itens). Datas, cliente e vendedor atualizam sem recalcular.
create or replace function interno.assinatura_venda(d jsonb) returns text
language sql immutable set search_path = '' as $$
  select md5(jsonb_build_array(d->'tipo', d->'vlr_liquido', d->'frete', d->'outras_desp', d->'comissao_vd',
    (select coalesce(jsonb_agg(jsonb_build_array(i->'codigo', i->'quantidade', i->'total_liquido') order by (i->>'ordem')::int), '[]'::jsonb)
       from jsonb_array_elements(coalesce(d->'itens','[]'::jsonb)) i))::text)
$$;

-- MC de uma venda do Santri com a mesma fórmula da Negociação.
-- Pagamento, arquiteto e Goyases vêm do pedido lançado pelo vendedor (se houver); sem pedido, MC sem taxa de cartão e sem RT.
-- Produto sem formação de preço na loja usa o "Custo compra" do Santri como custo.
create or replace function interno.calcular_mc_venda(p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v public.vendas_santri; p public.pedidos; par public.parametros_loja;
  ent jsonb; pag jsonb; r jsonb; itens jsonb; soma_it numeric; rec numeric;
  imp numeric; com numeric; rt numeric; goy numeric; mc numeric;
begin
  select * into v from public.vendas_santri where id = p_id;
  if v.id is null then return null; end if;
  select * into par from public.parametros_loja where loja_id = v.loja_id;
  if v.tipo = 'PED' and v.pedido_id is not null then
    select * into p from public.pedidos where id = v.pedido_id and status <> 'Cancelado';
  elsif v.tipo = 'DEV' and v.pedido_origem is not null then
    select pd.* into p from public.vendas_santri o join public.pedidos pd on pd.id = o.pedido_id and pd.status <> 'Cancelado'
      where o.loja_id = v.loja_id and o.tipo = 'PED' and o.numero = v.pedido_origem limit 1;
  end if;
  rec := coalesce(v.vlr_liquido, 0);
  if v.venda_direta then
    imp := coalesce(v.comissao_vd,0) * coalesce(par.imposto_venda_direta, 0.1633);
    com := rec * par.comissao_vendedor;
    rt  := case when coalesce(p.arquiteto,false) then rec * par.rt_arquiteto else 0 end;
    goy := case when coalesce(p.goyases,false) then rec * par.goyases else 0 end;
    mc  := coalesce(v.comissao_vd,0) - imp - com - rt - goy;
    r := jsonb_build_object('receita', round(rec,2), 'comissao_vd', v.comissao_vd, 'impostos', round(imp,2), 'comissao', round(com,2),
           'rt', round(rt,2), 'goyases', round(goy,2), 'custo_financeiro', 0, 'mc', round(mc,2),
           'mc_pct', case when rec > 0 then round(mc/rec,4) end, 'venda_direta', true, 'itens', '[]'::jsonb, 'avisos', '[]'::jsonb);
  else
    select coalesce(jsonb_agg(jsonb_build_object('produto_id', i.produto_id::text, 'ref', i.ordem, 'descricao', i.descricao,
               'quantidade', i.quantidade, 'preco_total', i.total_liquido)
             || case when coalesce(i.custo_compra_santri,0) > 0 and coalesce(i.quantidade,0) > 0
                      and not exists (select 1 from public.produto_precos pp where pp.loja_id = v.loja_id and pp.produto_id = i.produto_id
                                        and coalesce(pp.preco_tabela_fabrica,0) > 0)
                     then jsonb_build_object('custo_un', i.custo_compra_santri / i.quantidade) else '{}'::jsonb end
             order by i.ordem), '[]'::jsonb),
           coalesce(sum(i.total_liquido), 0)
      into itens, soma_it from public.vendas_santri_itens i where i.venda_id = v.id;
    pag := jsonb_build_object('modo','loja','entrada_valor', coalesce(p.entrada_valor,0), 'bandeira', p.bandeira, 'modalidade', coalesce(p.modalidade,''));
    if p.taxa_manual is not null then pag := pag || jsonb_build_object('taxa', p.taxa_manual); end if;
    ent := jsonb_build_object('loja_id', v.loja_id, 'arquiteto', coalesce(p.arquiteto,false), 'goyases', coalesce(p.goyases,false),
             'frete_cliente', greatest(rec - soma_it, 0), 'desconto_pct', 0, 'pagamento', pag, 'itens', itens);
    r := public.calcular_negociacao(ent);
  end if;
  r := r || jsonb_build_object('completo', v.venda_direta or p.id is not null, 'pedido_id', p.id);
  update public.vendas_santri set resultado = r,
    mc_origem = case when p.id is not null then 'santri+pedido' else 'santri' end
  where id = v.id;
  return r;
end $$;

-- Prévia: nada é gravado
create or replace function public.previa_importacao_vendas(p_importacao bigint) returns jsonb
language plpgsql set search_path = '' set statement_timeout to '120s' as $$
declare r jsonb;
begin
  if not interno.ve_todas_lojas() then raise exception 'Sem permissão'; end if;
  with s as (
    select (d->>'loja_id')::smallint loja_id, d->>'tipo' tipo, d->>'numero' numero,
           (d->>'data_fechamento')::timestamp df, coalesce((d->>'vlr_liquido')::numeric,0) vl,
           coalesce((d->>'comissao_vd')::numeric,0) > 0 vd, interno.assinatura_venda(d) sig, d
    from (select dados d from public.vendas_staging where importacao_id = p_importacao) z),
  j as (select s.*, v.id vid, v.assinatura vsig from s
        left join public.vendas_santri v on v.loja_id = s.loja_id and v.tipo = s.tipo and v.numero = s.numero),
  it as (select distinct i->>'codigo' cod from s, jsonb_array_elements(coalesce(s.d->'itens','[]'::jsonb)) i),
  pd as (select s.numero, s.vl, p.total_pedido from s
         join public.pedidos p on p.loja_id = s.loja_id and p.status <> 'Cancelado'
          and regexp_replace(p.numero_santri, '\D', '', 'g') = s.numero
         where s.tipo = 'PED')
  select jsonb_build_object(
    'no_arquivo', (select count(*) from s),
    'pedidos', (select count(*) from s where tipo = 'PED'),
    'devolucoes', (select count(*) from s where tipo = 'DEV'),
    'valor_pedidos', (select coalesce(sum(vl),0) from s where tipo = 'PED'),
    'valor_devolucoes', (select coalesce(sum(vl),0) from s where tipo = 'DEV'),
    'pva', (select count(*) from s where loja_id = 1), 'rv', (select count(*) from s where loja_id = 2),
    'de', (select min(df)::date from s), 'ate', (select max(df)::date from s),
    'sem_fechamento', (select count(*) from s where df is null),
    'venda_direta', (select count(*) from s where vd),
    'novos', (select count(*) from j where vid is null),
    'alterados', (select count(*) from j where vid is not null and vsig is distinct from sig),
    'iguais', (select count(*) from j where vid is not null and vsig = sig),
    'produtos_sem_cadastro', (select count(*) from it where cod !~ '^\d+$' or not exists (select 1 from public.produtos p where p.id = it.cod::bigint)),
    'itens_sem_custo', (select count(*) from s, jsonb_array_elements(coalesce(s.d->'itens','[]'::jsonb)) i
        where coalesce((i->>'custo_compra')::numeric,0) = 0 and not coalesce((s.d->>'comissao_vd')::numeric,0) > 0
          and not exists (select 1 from public.produto_precos pp where pp.loja_id = s.loja_id and (i->>'codigo') ~ '^\d+$'
                            and pp.produto_id = (i->>'codigo')::bigint and coalesce(pp.preco_tabela_fabrica,0) > 0)),
    'ja_lancados', (select count(*) from pd),
    'valores_divergentes', (select count(*) from pd where abs(coalesce(total_pedido,0) - vl) > 1)
  ) into r;
  return r;
end $$;

create or replace function public.aplicar_importacao_vendas(p_importacao bigint) returns jsonb
language plpgsql set search_path = '' set statement_timeout to '300s' as $$
declare res jsonb; d jsonb; vid bigint; vsig text; sig text;
  n_novos int := 0; n_alt int := 0; n_iguais int := 0; n_lig int := 0; recalc bigint[] := '{}'; ligados bigint[]; x bigint;
begin
  if not interno.ve_todas_lojas() then raise exception 'Sem permissão'; end if;
  res := public.previa_importacao_vendas(p_importacao);
  for d in select dados from public.vendas_staging where importacao_id = p_importacao order by id loop
    sig := interno.assinatura_venda(d); vid := null; vsig := null;
    select id, assinatura into vid, vsig from public.vendas_santri
      where loja_id = (d->>'loja_id')::smallint and tipo = d->>'tipo' and numero = d->>'numero';
    if vid is null then n_novos := n_novos + 1;
    elsif vsig is distinct from sig then n_alt := n_alt + 1;
    else n_iguais := n_iguais + 1; end if;
    insert into public.vendas_santri as v (loja_id, tipo, numero, pedido_origem, vendedor_santri, usuario_insercao,
      cliente_codigo, cliente_nome, cliente_doc, cliente_telefone, cliente_email, data_fechamento, data_recebimento,
      vlr_produtos, frete, outras_desp, desconto, vlr_liquido, custo_santri, custo_compra_santri, prazo_medio, comissao_vd,
      venda_direta, assinatura, importacao_id)
    values ((d->>'loja_id')::smallint, d->>'tipo', d->>'numero', nullif(d->>'pedido_origem',''), d->>'vendedor', d->>'usuario_insercao',
      d->>'cliente_codigo', d->>'cliente_nome', d->>'cliente_doc', d->>'cliente_telefone', d->>'cliente_email',
      (d->>'data_fechamento')::timestamp, (d->>'data_recebimento')::timestamp,
      (d->>'vlr_produtos')::numeric, (d->>'frete')::numeric, (d->>'outras_desp')::numeric, (d->>'desconto')::numeric,
      (d->>'vlr_liquido')::numeric, (d->>'custo')::numeric, (d->>'custo_compra')::numeric, (d->>'prazo_medio')::numeric,
      (d->>'comissao_vd')::numeric, coalesce((d->>'comissao_vd')::numeric,0) > 0, sig, p_importacao)
    on conflict (loja_id, tipo, numero) do update set
      pedido_origem = excluded.pedido_origem, vendedor_santri = excluded.vendedor_santri, usuario_insercao = excluded.usuario_insercao,
      cliente_codigo = excluded.cliente_codigo, cliente_nome = excluded.cliente_nome, cliente_doc = excluded.cliente_doc,
      cliente_telefone = excluded.cliente_telefone, cliente_email = excluded.cliente_email,
      data_fechamento = excluded.data_fechamento, data_recebimento = excluded.data_recebimento,
      vlr_produtos = excluded.vlr_produtos, frete = excluded.frete, outras_desp = excluded.outras_desp, desconto = excluded.desconto,
      vlr_liquido = excluded.vlr_liquido, custo_santri = excluded.custo_santri, custo_compra_santri = excluded.custo_compra_santri,
      prazo_medio = excluded.prazo_medio, comissao_vd = excluded.comissao_vd, venda_direta = excluded.venda_direta,
      assinatura = excluded.assinatura, importacao_id = excluded.importacao_id, atualizado_em = now()
    returning id into vid;
    if vsig is null or vsig is distinct from sig then
      delete from public.vendas_santri_itens where venda_id = vid;
      insert into public.vendas_santri_itens (venda_id, ordem, produto_id, codigo, descricao, marca, quantidade, preco_unitario,
        total_bruto, juros_desc, total_liquido, custo_santri, custo_compra_santri)
      select vid, (i->>'ordem')::int,
        (select p.id from public.produtos p where (i->>'codigo') ~ '^\d+$' and p.id = (i->>'codigo')::bigint),
        i->>'codigo', i->>'descricao', i->>'marca', (i->>'quantidade')::numeric, (i->>'preco_unitario')::numeric,
        (i->>'total_bruto')::numeric, (i->>'juros_desc')::numeric, (i->>'total_liquido')::numeric,
        (i->>'custo')::numeric, (i->>'custo_compra')::numeric
      from jsonb_array_elements(coalesce(d->'itens','[]'::jsonb)) i;
      recalc := recalc || vid;
    else
      -- mesma venda: só completa o custo de compra que faltava (ex.: arquivo anterior exportado com custo médio)
      update public.vendas_santri_itens t set custo_compra_santri = (i->>'custo_compra')::numeric
      from jsonb_array_elements(coalesce(d->'itens','[]'::jsonb)) i
      where t.venda_id = vid and t.ordem = (i->>'ordem')::int
        and coalesce(t.custo_compra_santri,0) = 0 and coalesce((i->>'custo_compra')::numeric,0) > 0;
      if found then recalc := recalc || vid; end if;
    end if;
  end loop;
  -- liga aos pedidos lançados pelo vendedor (mesmo número, mesma loja)
  with lig as (
    update public.vendas_santri v set pedido_id = p.id
    from public.pedidos p
    where v.tipo = 'PED' and v.pedido_id is null and p.loja_id = v.loja_id and p.status <> 'Cancelado'
      and regexp_replace(p.numero_santri, '\D', '', 'g') = v.numero
    returning v.id)
  select coalesce(array_agg(id), '{}') into ligados from lig;
  n_lig := cardinality(ligados); recalc := recalc || ligados;
  for x in select distinct unnest(recalc) union select id from public.vendas_santri where resultado is null loop
    perform interno.calcular_mc_venda(x);
  end loop;
  delete from public.vendas_staging where importacao_id = p_importacao;
  res := res || jsonb_build_object('novos', n_novos, 'alterados', n_alt, 'iguais', n_iguais, 'ligados_agora', n_lig);
  update public.importacoes set status = 'aplicada', resumo = res, linhas = (res->>'no_arquivo')::int where id = p_importacao;
  return res;
end $$;

-- Pedido lançado/alterado/cancelado pelo vendedor → liga à venda do Santri de mesmo número e recalcula a MC
create or replace function interno.pedido_liga_venda() returns trigger
language plpgsql security definer set search_path = '' as $$
declare x bigint; num text := regexp_replace(coalesce(new.numero_santri,''), '\D', '', 'g');
begin
  -- solta vendas que apontavam para este pedido e não batem mais (cancelado, número ou loja trocados)
  for x in select id from public.vendas_santri where pedido_id = new.id
             and (new.status = 'Cancelado' or numero <> num or loja_id <> new.loja_id) loop
    update public.vendas_santri set pedido_id = null where id = x;
    perform interno.calcular_mc_venda(x);
  end loop;
  if new.status <> 'Cancelado' and num <> '' then
    update public.vendas_santri set pedido_id = new.id
      where tipo = 'PED' and loja_id = new.loja_id and numero = num and pedido_id is distinct from new.id;
    for x in select id from public.vendas_santri
              where loja_id = new.loja_id and ((tipo = 'PED' and numero = num) or (tipo = 'DEV' and pedido_origem = num)) loop
      perform interno.calcular_mc_venda(x);
    end loop;
  end if;
  return new;
end $$;

create trigger pedidos_liga_venda after insert or update of status, numero_santri, loja_id, arquiteto, goyases, bandeira, modalidade, taxa_manual, entrada_valor
  on public.pedidos for each row execute function interno.pedido_liga_venda();

-- Vendas do período: Santri (PED soma, DEV subtrai) + pedidos lançados que ainda não vieram no relatório
create or replace function interno.vendas_periodo(p_lojas smallint[], p_ini date, p_fim date)
returns table(loja_id smallint, vendedor_id uuid, vendedor_nome text, d date, receita numeric, mc numeric, tipo text, lancado boolean, completo boolean)
language sql stable security definer set search_path = '' as $$
  select v.loja_id, coalesce(c.vendedor_id, c2.vendedor_id, u.id),
         coalesce(uc.nome, uc2.nome, u.nome, initcap(lower(trim(v.vendedor_santri)))),
         v.data_fechamento::date,
         s.sinal * coalesce((v.resultado->>'receita')::numeric, v.vlr_liquido, 0),
         s.sinal * coalesce((v.resultado->>'mc')::numeric, 0),
         v.tipo, v.pedido_id is not null, coalesce((v.resultado->>'completo')::boolean, false)
  from public.vendas_santri v
  cross join lateral (select case when v.tipo = 'DEV' then -1 else 1 end sinal) s
  left join public.pedidos p on p.id = v.pedido_id
  left join public.capas c on c.id = p.capa_id
  left join public.usuarios uc on uc.id = c.vendedor_id
  left join lateral (select pd.capa_id from public.vendas_santri o join public.pedidos pd on pd.id = o.pedido_id
                     where v.tipo = 'DEV' and o.loja_id = v.loja_id and o.tipo = 'PED' and o.numero = v.pedido_origem limit 1) o on true
  left join public.capas c2 on c2.id = o.capa_id
  left join public.usuarios uc2 on uc2.id = c2.vendedor_id
  left join lateral (select x.id, x.nome from public.usuarios x
                     where x.nome_santri is not null and upper(trim(x.nome_santri)) = upper(trim(v.vendedor_santri))
                     order by (x.loja_id = v.loja_id) desc nulls last limit 1) u on true
  where v.loja_id = any(p_lojas) and v.data_fechamento >= p_ini and v.data_fechamento < p_fim
  union all
  select p.loja_id, c.vendedor_id, uc.nome, p.data_fechamento,
         coalesce((p.resultado->>'receita')::numeric, p.total_pedido, 0), coalesce((p.resultado->>'mc')::numeric, 0),
         'PED', true, true
  from public.pedidos p
  left join public.capas c on c.id = p.capa_id
  left join public.usuarios uc on uc.id = c.vendedor_id
  where p.loja_id = any(p_lojas) and p.status <> 'Cancelado' and p.data_fechamento >= p_ini and p.data_fechamento < p_fim
    and not exists (select 1 from public.vendas_santri v where v.pedido_id = p.id)
$$;

create or replace function public.mc_do_mes(p_loja smallint) returns jsonb
language sql stable security definer set search_path = '' as $$
  select jsonb_build_object(
    'mc_fechada', coalesce(sum(x.mc),0),
    'receita_fechada', coalesce(sum(x.receita),0),
    'pedidos', count(*) filter (where x.tipo = 'PED'),
    'pe_mc_mensal', (select pe_mc_mensal from public.parametros_loja where loja_id = p_loja))
  from interno.vendas_periodo(array[p_loja], date_trunc('month', now())::date, (date_trunc('month', now()) + interval '1 month')::date) x
  where interno.e_ativo()
$$;

create or replace function public.painel_gerencia(p_loja smallint, p_mes date) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  ini date := date_trunc('month', coalesce(p_mes, current_date))::date;
  fim date := (date_trunc('month', coalesce(p_mes, current_date)) + interval '1 month')::date;
  lojas smallint[];
  res jsonb;
begin
  if not interno.e_ativo() then raise exception 'acesso negado'; end if;
  if coalesce(p_loja,0) = 0 then
    if not interno.le_todas_lojas() then raise exception 'sem acesso às duas lojas'; end if;
    select array_agg(id) into lojas from public.lojas;
  else
    if not (interno.le_todas_lojas() or p_loja = interno.minha_loja()) then raise exception 'sem acesso a esta loja'; end if;
    lojas := array[p_loja];
  end if;

  with
  ped as (
    select x.*, coalesce(x.vendedor_id::text, 'S:' || upper(coalesce(x.vendedor_nome, '?'))) vk
    from interno.vendas_periodo(lojas, ini, fim) x),
  ati as (
    select a.loja_id, a.usuario_id vendedor_id, a.tipo from public.atividades a
    where a.loja_id = any(lojas) and a.data >= ini and a.data < fim),
  cap as (
    select c.loja_id, c.vendedor_id, c.status from public.capas c
    where c.loja_id = any(lojas) and c.data_abertura >= ini and c.data_abertura < fim),
  orc as (
    select distinct on (c.loja_id, o.numero_santri) c.loja_id, c.vendedor_id, o.status, o.motivo_perda, o.quente,
           coalesce(o.valor_provavel, o.valor_total_pdf, 0) valor
    from public.orcamentos o join public.capas c on c.id = o.capa_id
    where c.loja_id = any(lojas) and o.data_emissao >= ini and o.data_emissao < fim
    order by c.loja_id, o.numero_santri, o.criado_em desc),
  aberto as (
    select * from (
      select distinct on (c.loja_id, o.numero_santri) c.loja_id, c.vendedor_id, o.status, o.quente, o.data_validade,
             coalesce(o.valor_provavel, o.valor_total_pdf, 0) valor
      from public.orcamentos o join public.capas c on c.id = o.capa_id
      where c.loja_id = any(lojas) and c.status not in ('Perdida','Ganha (virou pedido)')
      order by c.loja_id, o.numero_santri, o.criado_em desc) z where status = 'Em negociação'),
  pend as (  -- vendas do Santri sem pedido lançado no sistema, a partir da data de corte da loja
    select x.*, coalesce(x.vendedor_id::text, 'S:' || upper(coalesce(x.vendedor_nome, '?'))) vk
    from public.parametros_loja pl
    cross join lateral interno.vendas_periodo(array[pl.loja_id], coalesce(pl.pendencias_desde, ini), (current_date + 1)) x
    where pl.loja_id = any(lojas) and x.tipo = 'PED' and not x.lancado),
  vend as (
    select u.id::text vk, u.id, u.nome, u.loja_id from public.usuarios u
    where u.ativo and (u.loja_id = any(lojas)) and u.papel in ('vendedor','gerente')
    union
    select distinct u.id::text, u.id, u.nome, x.loja_id from (
      select vendedor_id, loja_id from ped where vendedor_id is not null union select vendedor_id, loja_id from ati
      union select vendedor_id, loja_id from cap union select vendedor_id, loja_id from orc) x
    join public.usuarios u on u.id = x.vendedor_id
    union
    select distinct vk, null::uuid, vendedor_nome, loja_id from ped where vendedor_id is null and vendedor_nome is not null),
  por_vend as (
    select v.id, v.vk, v.nome, v.loja_id, v.id is null sem_usuario,
      (select coalesce(sum(receita),0) from ped where vk = v.vk and loja_id = v.loja_id) faturamento,
      (select coalesce(sum(mc),0) from ped where vk = v.vk and loja_id = v.loja_id) mc,
      (select count(*) from ped where vk = v.vk and loja_id = v.loja_id and tipo = 'PED') pedidos,
      (select count(*) from ped where vk = v.vk and loja_id = v.loja_id and tipo = 'PED' and not completo) mc_parcial,
      (select count(*) from pend where vk = v.vk and loja_id = v.loja_id) pendentes,
      (select count(*) from ati where vendedor_id = v.id and loja_id = v.loja_id and tipo <> 'Orçamento enviado') atividades,
      (select count(*) from cap where vendedor_id = v.id and loja_id = v.loja_id) capas_novas,
      (select count(*) from orc where vendedor_id = v.id and loja_id = v.loja_id) orcamentos,
      (select count(*) from orc where vendedor_id = v.id and loja_id = v.loja_id and status = 'Ganho') ganhos,
      (select count(*) from orc where vendedor_id = v.id and loja_id = v.loja_id and status = 'Perdido') perdidos,
      (select coalesce(sum(valor),0) from aberto where vendedor_id = v.id and loja_id = v.loja_id) carteira,
      (select count(*) from aberto where vendedor_id = v.id and loja_id = v.loja_id and quente) quentes,
      m.faturamento meta_faturamento, m.mc meta_mc, m.mc_pct_min meta_mc_pct_min, m.atividades meta_atividades, m.capas_novas meta_capas_novas
    from vend v left join public.metas m on v.id is not null and m.usuario_id = v.id and m.loja_id = v.loja_id and m.mes = ini),
  por_loja as (
    select l.id, l.codigo, l.nome,
      (select coalesce(sum(receita),0) from ped where loja_id = l.id) faturamento,
      (select coalesce(sum(mc),0) from ped where loja_id = l.id) mc,
      (select count(*) from ped where loja_id = l.id and tipo = 'PED') pedidos,
      (select coalesce(-sum(receita),0) from ped where loja_id = l.id and tipo = 'DEV') devolucoes,
      (select count(*) from ped where loja_id = l.id and tipo = 'DEV') devolucoes_qtd,
      (select count(*) from ped where loja_id = l.id and tipo = 'PED' and not completo) mc_parcial,
      (select count(*) from ped where loja_id = l.id and vendedor_id is null and vendedor_nome is null) pedidos_sem_vendedor,
      (select count(distinct vk) from ped where loja_id = l.id and vendedor_id is null and vendedor_nome is not null) vendedores_sem_usuario,
      (select count(*) from pend where loja_id = l.id) vendas_pendentes,
      (select max(data_fechamento) from public.vendas_santri where loja_id = l.id) santri_ate,
      (select count(*) from ati where loja_id = l.id and tipo <> 'Orçamento enviado') atividades,
      (select count(*) from cap where loja_id = l.id) capas_novas,
      (select count(*) from orc where loja_id = l.id) orcamentos,
      (select coalesce(sum(valor),0) from orc where loja_id = l.id) orcamentos_valor,
      (select count(*) from orc where loja_id = l.id and status = 'Ganho') ganhos,
      (select count(*) from orc where loja_id = l.id and status = 'Perdido') perdidos,
      (select coalesce(sum(valor),0) from aberto where loja_id = l.id) carteira,
      (select count(*) from aberto where loja_id = l.id) carteira_qtd,
      (select count(*) from aberto where loja_id = l.id and quente) quentes,
      (select count(*) from aberto where loja_id = l.id and data_validade < current_date) vencidos,
      pl.pe_mc_mensal, pl.pendencias_desde,
      m.faturamento meta_faturamento, m.mc meta_mc, m.mc_pct_min meta_mc_pct_min, m.atividades meta_atividades, m.capas_novas meta_capas_novas
    from public.lojas l
    left join public.parametros_loja pl on pl.loja_id = l.id
    left join public.metas m on m.loja_id = l.id and m.usuario_id is null and m.mes = ini
    where l.id = any(lojas))
  select jsonb_build_object(
    'mes', ini,
    'hoje', current_date,
    'ultima_importacao_vendas', (select max(criado_em) from public.importacoes where tipo = 'vendas' and status = 'aplicada'),
    'lojas', (select coalesce(jsonb_agg(to_jsonb(x) order by x.id), '[]') from por_loja x),
    'vendedores', (select coalesce(jsonb_agg(to_jsonb(x) order by x.mc desc, x.nome), '[]') from por_vend x),
    'diario', (select coalesce(jsonb_agg(jsonb_build_object('d', d, 'receita', r, 'mc', m) order by d), '[]')
               from (select d, sum(receita) r, sum(mc) m from ped group by d) z),
    'perdas', (select coalesce(jsonb_agg(jsonb_build_object('motivo', mo, 'qtd', q, 'valor', vl) order by q desc), '[]')
               from (select coalesce(motivo_perda,'Sem motivo') mo, count(*) q, sum(valor) vl from orc where status = 'Perdido' group by 1) z),
    'atividades_tipo', (select coalesce(jsonb_agg(jsonb_build_object('tipo', tipo, 'qtd', q) order by q desc), '[]')
               from (select tipo, count(*) q from ati group by tipo) z)
  ) into res;
  return res;
end $$;

